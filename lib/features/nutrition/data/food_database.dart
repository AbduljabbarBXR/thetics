FoodItem? builtInFoodById(String id) {
  for (final food in builtInFoods) {
    if (food.id == id) return food;
  }
  return null;
}

List<FoodItem> searchFoods({
  required String query,
  required String category,
  required List<FoodItem> customFoods,
}) {
  final all = [...customFoods, ...builtInFoods];
  final normalized = query.trim().toLowerCase();
  return all.where((food) {
    final matchesCategory = category == 'All' ||
        food.category.toLowerCase() == category.toLowerCase();
    final matchesQuery = normalized.isEmpty ||
        food.name.toLowerCase().contains(normalized) ||
        (food.brand?.toLowerCase().contains(normalized) ?? false);
    return matchesCategory && matchesQuery;
  }).toList();
}
